import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {harness,dataOf} from './harness.mjs';
const browser=await harness();
const scope='教育经历 / 第1条';
const call=async(name,args)=>dataOf(await browser.call(name,{page_id:browser.pageId,scope,...args}));
const oracle=()=>browser.evalPage('() => window.fixtureOracle()');
const results=[];
try {
  await browser.open('ud-contract');
  const longText='负责方案设计与实现，验证跨组件数据在重新渲染之后保持一致。\n'.repeat(12);
  const longResult=await call('form_fill_fields',{fields:[{field:'经历描述',scope,value:longText}]});
  assert.equal(longResult.results[0].status,'filled');
  await call('form_activate',{target:'重新渲染',scope:'page',intent:'open'});
  assert.equal((await oracle()).values[0].经历描述,longText,'long text must reach React state');
  const again=await call('form_fill_fields',{fields:[{field:'经历描述',scope,value:longText}]});
  assert.equal(again.results[0].status,'unchanged');
  const rejected=await call('form_fill_fields',{fields:[{field:'拒绝描述',scope,value:longText}]});
  assert.equal(rejected.results[0].status,'postcondition_failed');
  results.push('long text survives React rerender; same-value retry is idempotent; blur rejection fails');
  const filled=await call('form_fill_fields',{fields:[{field:'学校名称',scope,value:'示例大学'}]});
  assert.equal(filled.results[0].status,'filled');
  assert.equal((await oracle()).values[0].学校名称,'示例大学');
  for(const [field,value] of [['学历类型','统招全日制'],['学历','本科']]){
    const selected=await call('form_select_option',{field,value});assert.equal(selected.status,'verified_ui',JSON.stringify(selected));
    assert.equal((await oracle()).values[0][field],value);
  }
  results.push('React state accepts plain input and UD-shape selects');
  const animated=await call('form_select_option',{field:'渐隐学历',value:'本科'});
  assert.equal(animated.status,'verified_ui',JSON.stringify(animated));
  assert.equal((await oracle()).values[0].渐隐学历,'本科');
  assert.equal(await browser.evalPage('() => document.querySelectorAll(".ud__select__dropdown").length'),0);
  results.push('select waits for a closing portal without aria-expanded');
  const animatedRollback=await call('form_select_option',{field:'渐隐回滚学历',value:'本科'});
  assert.equal(animatedRollback.error?.code,'postcondition_failed',JSON.stringify(animatedRollback));
  assert.equal((await oracle()).values[0].渐隐回滚学历,'');
  results.push('rollback during portal exit is rejected');
  const date=await call('form_set_date',{field:'起止时间',range:{start:'2020-09',end:'2024-06'}});
  assert.equal(date.status,'verified_ui',JSON.stringify(date));
  assert.deepEqual((await oracle()).values[0].起止时间,['2020-09','2024-06']);
  await call('form_activate',{target:'重新渲染',scope:'page',intent:'open'});
  assert.deepEqual((await oracle()).values[0].起止时间,['2020-09','2024-06']);
  assert.deepEqual((await oracle()).values[1],{});
  results.push('React rerender keeps values and the other record isolated');
  const rollback=await call('form_select_option',{field:'回滚学历',value:'本科'});
  assert.equal(rollback.error?.code,'postcondition_failed',JSON.stringify(rollback));
  assert.equal((await oracle()).values[0].回滚学历,'');
  results.push('blur rollback is rejected');
  const ambiguous=await call('form_select_option',{field:'歧义学历',value:'本科'});
  assert.equal(ambiguous.error?.code,'option_ambiguous');
  results.push('duplicate option labels are rejected');
  await browser.open('ud-contract');
  const rejectedDate=await call('form_set_date',{field:'回滚时间',range:{start:'2020-09',end:'2024-06'}});
  assert.notEqual(rejectedDate.status,'verified_ui');assert(rejectedDate.error,JSON.stringify(rejectedDate));
  assert.equal((await oracle()).values[0].回滚时间,undefined);
  results.push('React rejects date updates without false success');
  await browser.open('ud-contract');
  const disabled=await call('form_set_date',{field:'受限时间',range:{start:'2024-02',end:'2024-06'}});
  assert.equal(disabled.error?.code,'constraint_violation',JSON.stringify(disabled));
  assert.equal((await oracle()).values[0].受限时间,undefined);
  results.push('disabled month is rejected before committing');
  await browser.open('ud-contract');
  await browser.evalPage(`() => {for(const e of document.querySelectorAll('.apply-form-array-card__contract:first-child input'))e.value='';const card=document.querySelector('.apply-form-array-card__contract');const range=card.querySelector('.throne-biz-date-range-picker-wrapper');range.querySelectorAll('input')[0].value='2020-09';range.querySelectorAll('input')[1].value='2024-06';return true;}`);
  const spoofed=await call('form_set_date',{field:'起止时间',range:{start:'2020-09',end:'2024-06'}});
  assert.notEqual(spoofed.status,'unchanged');assert.notEqual(spoofed.status,'verified_ui');
  assert.equal((await oracle()).values[0].起止时间,undefined);
  results.push('DOM-only date spoof fails committed-selection verification');
  const report={passed:true,framework:'React 18',component:'original behavioral fixture, not original UD package',results};
  const resultDirectory=resolve(import.meta.dirname,'../../.local-archive/offline-sites');
  await mkdir(resultDirectory,{recursive:true});
  await writeFile(resolve(resultDirectory,'UD-CONTRACT-RESULTS.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
